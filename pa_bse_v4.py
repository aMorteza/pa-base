def pa_bse(seed,hybrid=True,init_frac=None,max_iter=None,fixed_sigma=None):
    # baseline_mode is ON only for the explicit sigma=0 reference run.
    _bm = (fixed_sigma is not None and fixed_sigma <= 0)
    # fixed_sigma=0.0 restricts to the sigma=0 slice -> the BSE baseline.
    init_frac=CFG.init_frac if init_frac is None else init_frac; max_iter=max_iter or CFG.max_iter
    if fixed_sigma is not None:
        idx=[i for i,(l,P,s) in enumerate(CAND3_PHYS) if abs(s-fixed_sigma)<1e-9]
    else:
        # private search: sigma=0 is NOT a candidate (it is the baseline, not a
        # private configuration), so the optimizer cannot degenerate to no-privacy.
        idx=[i for i,(l,P,s) in enumerate(CAND3_PHYS) if s>0]
    C=CAND3[idx]; PH=[CAND3_PHYS[i] for i in idx]; PN=PEN3[idx]
    rng=np.random.default_rng(seed); N0=max(4,int(round(init_frac*len(C))))
    ii=rng.choice(len(C),N0,replace=False); hist,A,Y=[],[],[]
    for i in ii:
        l,P,s=PH[i]; r=evaluate_priv(l,P,s,baseline_mode=_bm); r["phase"]="init"; hist.append(r); A.append(C[i]); Y.append(r["U"])
    feas=[i for i,r in enumerate(hist) if r["feasible"]]
    bi=max(feas,key=lambda i:hist[i]["U"]) if feas else int(np.argmax(Y))
    a_s,U_s,nc=hist[bi],hist[bi]["U"],0
    for n in range(1,max_iter+1):
        gp=_gp(A,Y,seed); mu,sd=gp.predict(C,return_std=True); sd=np.maximum(sd,1e-9)
        z=(mu-U_s-CFG.xi_ei)/sd; ei=sd*(z*norm.cdf(z)+norm.pdf(z)); ucb=mu+CFG.kappa_ucb*sd
        base=np.where(ei>1e-8,ei,ucb)
        if hybrid:
            acq=100.0*base-CFG.lam_p*PN; rej=mu<CFG.min_accuracy
            if not rej.all(): acq=np.where(rej,-np.inf,acq)
        else: acq=ei
        i2=int(np.argmax(acq)); l,P,s=PH[i2]; r=evaluate_priv(l,P,s,baseline_mode=_bm); r["phase"]="bo"
