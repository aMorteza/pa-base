# ---- render a DataFrame as a figure (PNG + PDF) for slides / the paper ----
def render_table(df, basename, title=None, max_rows=28, col_width=1.6, row_height=0.42,
                 fontsize=9, highlight_rows=None, index=False):
    """Save a DataFrame as a styled table image. highlight_rows = list of row indices
    to shade (e.g. the DELTA row or the chosen operating point)."""
    import matplotlib.pyplot as _plt
    import pandas as _pd
    d = df.reset_index() if index else df.copy()
    truncated = False
    if len(d) > max_rows:
        d = d.head(max_rows); truncated = True
    ncol, nrow = len(d.columns), len(d)
    fig, ax = _plt.subplots(figsize=(min(col_width*ncol, 22), row_height*(nrow+2)+ (0.5 if title else 0)))
    ax.axis("off")
    cells = [[("" if _pd.isna(v) else str(v)) for v in row] for row in d.values]
    tbl = ax.table(cellText=cells, colLabels=list(d.columns), loc="center", cellLoc="center")
    tbl.auto_set_font_size(False); tbl.set_fontsize(fontsize); tbl.scale(1, 1.35)
    tbl.auto_set_column_width(col=list(range(ncol)))   # fit content, avoid clipping
    # header styling
    for j in range(ncol):
        c = tbl[0, j]; c.set_facecolor("#40466e"); c.set_text_props(color="white", weight="bold")
    # zebra striping + optional highlights
    for i in range(1, nrow+1):
        for j in range(ncol):
            c = tbl[i, j]
            if highlight_rows and (i-1) in highlight_rows:
                c.set_facecolor("#fff3bf")
            elif i % 2 == 0:
                c.set_facecolor("#f2f2f2")
    if title:
        ax.set_title(title + ("  (truncated)" if truncated else ""), fontweight="bold", pad=12)
    _plt.tight_layout()
    savefig_both(basename, fig=fig)
    _plt.close(fig)
    return basename

def savefig_both(basename, fig=None, dpi=140):
    import matplotlib.pyplot as _plt
    f = fig or _plt.gcf()
    base = basename[:-4] if basename.endswith('.png') else basename
    f.savefig(f"{base}.png", dpi=dpi, bbox_inches="tight")
    f.savefig(f"{base}.pdf", bbox_inches="tight")     # vector for LaTeX
    return base


