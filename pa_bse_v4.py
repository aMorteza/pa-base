"""## Privacy mechanism (draft eq. for the per-element RDP budget)
$\bar\epsilon_{\mathrm{DP}}(\sigma)=\tfrac12\log_2\!\big(1+c_0^2/\sigma^2\big)$ (per element),
total $\epsilon(l,\sigma)=d_l\,\bar\epsilon_{\mathrm{DP}}(\sigma)$. Constraint: $\bar\epsilon_{\mathrm{DP}}(\sigma)\le\bar\epsilon$.
"""

#@title 7. Privacy mechanism + RDP budget (draft symbols)
def privatize(z, sigma, l=None):
    # sigma=0 -> return z unchanged so the sigma=0 slice equals the baseline exactly.
    if sigma <= 0: return z
    f=z.flatten(1); d=f.shape[1]; C=CFG.c0*(d**0.5)          # C_l = c0*sqrt(d_l)
    n=f.norm(dim=1,keepdim=True).clamp_min(1e-12); f=f*torch.clamp(C/n,max=1.0)
    return (f+torch.randn_like(f)*sigma).view_as(z)
def eps_bar_dp(sigma):
    # PER-ELEMENT RDP budget (draft: bar-epsilon_DP(sigma)); layer-independent.
    if sigma<=0: return np.inf
    return 0.5*np.log2(1.0+(CFG.c0**2)/(sigma**2))
def eps_total(l, sigma):
    # TOTAL budget eps = d_l * per-element (draft: epsilon = d_l * bar-epsilon).
    if sigma<=0: return np.inf
    return D_ELEMENTS[int(l)]*eps_bar_dp(sigma)
