#@title 9. Privacy-aware evaluate + penalty (constraint: eps_bar_dp(sigma) <= eps_bar)
def evaluate(l,P,g=None):
    l=int(np.clip(round(l),0,CFG.n_split_layers-1))
    t_md,t_s=tau_device(l),tau_server(l); tt_full=tau_transmit_full(l,P,g)
    t_e=CFG.tau_max-t_md-t_s
    if t_e<=0: drop,tt=1.0,0.0
    elif tt_full<=t_e: drop,tt=0.0,tt_full
    else: drop,tt=float(np.clip(1-t_e/tt_full,0,1)),t_e
    E=comp_energy(l)+P*tt; delay=t_md+tt+t_s
    return dict(l=l,P_t=P,E=E,E_c=comp_energy(l),E_t=P*tt,delay=delay,drop=drop,
                feasible=(E<=CFG.E_max and delay<=CFG.tau_max+1e-9))
def evaluate_priv(l,P,sigma,g=None,baseline_mode=False):
    b=evaluate(l,P,g); l=b["l"]
    U=accuracy_lookup_priv(l,b["drop"],sigma)
    eb=eps_bar_dp(sigma); et=eps_total(l,sigma)
    # The NON-PRIVATE BASELINE (sigma=0) is the reference point and is not subject
    # to the privacy constraint, which it cannot satisfy by definition. But that
    # exemption must apply ONLY when we are deliberately evaluating the baseline --
    # otherwise the privacy-aware optimizer would simply choose sigma=0 (highest
    # accuracy, "feasible") and degenerate into the baseline. Callers therefore opt
    # in explicitly via baseline_mode=True; the private search never does.
    if sigma <= 0:
        ok = bool(baseline_mode)        # exempt ONLY in explicit baseline mode
    else:
        ok = eb <= CFG.eps_bar
    return dict(b, sigma=float(sigma), U=U, eps_bar=eb, eps_total=et,
                priv_feasible=bool(ok), feasible=bool(b["feasible"] and ok))
def penalty_priv(l,P,sigma,g=None,baseline_mode=False):
    r=evaluate_priv(l,P,sigma,g,baseline_mode); e=max(0,r["E"]-CFG.E_max); d=max(0,r["delay"]-CFG.tau_max)
    p=max(0,r["eps_bar"]-CFG.eps_bar) if np.isfinite(r["eps_bar"]) else 1e6
    return e+d+CFG.lam_priv*p
